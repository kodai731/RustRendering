"""Write the polarity term table the engine embeds, derived from exemplars alone.

Run after editing `exemplars.jsonl`; the table is generated output, not something
to hand-edit. Writing it into `src/orchestrator/data/` is what lets the Rust
tie-break and the Python evaluation read one file.

Run:
    .venv-orchestrator-eval/bin/python scripts/orchestrator_eval/derive_polarity_terms.py
"""

import argparse
import json
from pathlib import Path

from dataset import read_jsonl
from polarity import TABLE_PATH, derive_table

SCRIPT_DIR = Path(__file__).resolve().parent

HEADER_COMMENT = (
    "Generated by scripts/orchestrator_eval/derive_polarity_terms.py from "
    "exemplars.jsonl. Do not hand-edit: a term here must be one the exemplars "
    "already separate, otherwise the tie-break encodes a guess the measured "
    "numbers never saw. Terms match as substrings of the normalized utterance."
)

DEFAULT_MIN_SUPPORT = 1


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--min-support", type=int, default=DEFAULT_MIN_SUPPORT)
    parser.add_argument("--output", default=str(TABLE_PATH))
    arguments = parser.parse_args()

    exemplars = read_jsonl(SCRIPT_DIR / "exemplars.jsonl")
    table = {"_comment": HEADER_COMMENT, **derive_table(exemplars, arguments.min_support)}

    output_path = Path(arguments.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(table, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    term_count = sum(len(terms) for group in table["groups"].values() for terms in group.values())
    print(f"{output_path} — {len(table['groups'])} groups, {term_count} terms")
    for name, members in table["groups"].items():
        sizes = ", ".join(f"{route.split(':')[-1]}={len(terms)}" for route, terms in members.items())
        print(f"  {name:<20} {sizes}")


if __name__ == "__main__":
    main()
