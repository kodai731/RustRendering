"""Record what the Python tie-break answers, so the Rust one can be held to it.

The measured route accuracy was produced by `polarity.py`, not by
`src/orchestrator/systems/polarity_tiebreak.rs`. Two implementations of one rule
drift silently: a difference in normalization, in substring semantics or in which
routes share an axis would move the engine off the number the design documents
quote, and nothing would fail. This writes the Python answers to a file the Rust
test asserts against, which makes any such difference a failing test.

The direction matters. Regenerating cannot absorb a Rust change, because this
script never runs Rust; it can only record a deliberate Python change, which is
the correct outcome for a reference implementation.

Every utterance the repository has is covered — exemplars, devset and heldout —
because the terms are derived from the exemplars and the confusions live in the
datasets, so those are the strings whose behaviour is worth pinning.

Run after `derive_polarity_terms.py`:
    .venv-orchestrator-eval/bin/python scripts/orchestrator_eval/export_tiebreak_cases.py
"""

import argparse
import json
from itertools import permutations
from pathlib import Path

from dataset import DATASET_PATHS, read_jsonl
from normalize import normalize_utterance
from polarity import TABLE_PATH, PolarityTieBreaker, load_tie_breaker

SCRIPT_DIR = Path(__file__).resolve().parent
CASES_PATH = TABLE_PATH.parent / "polarity_tiebreak_cases.json"

HEADER_COMMENT = (
    "Generated by scripts/orchestrator_eval/export_tiebreak_cases.py. Test data: "
    "the answers scripts/orchestrator_eval/polarity.py gives, which the Rust "
    "tie-break must reproduce exactly. Regenerate after derive_polarity_terms.py. "
    "A resolution is [leader, runner_up, winner] in route ids, the leader and "
    "runner_up being the encoder's first two in that order."
)


def collect_utterances() -> list[str]:
    sources = [SCRIPT_DIR / "exemplars.jsonl", *DATASET_PATHS.values()]
    seen: dict[str, None] = {}
    for path in sources:
        for row in read_jsonl(path):
            seen.setdefault(row["utterance"], None)
    return list(seen)


def find_axes_with_evidence(breaker: PolarityTieBreaker, normalized: str) -> list[str]:
    return [
        axis
        for axis, members in breaker.members_by_axis.items()
        if any(breaker.count_evidence(normalized, member) for member in members)
    ]


def build_cross_axis_pairs(
    breaker: PolarityTieBreaker, involved: list[str]
) -> list[tuple[str, str]]:
    """Pairs drawn from two different axes, which must never be reordered.

    Without these the file would only ever exercise the branch where the two
    candidates do share an axis, and a Rust lookup that matched on route rather
    than on axis would pass.
    """
    axes = list(breaker.members_by_axis)
    pairs = []
    for axis in involved:
        other = axes[(axes.index(axis) + 1) % len(axes)]
        leader = breaker.members_by_axis[axis][0]
        follower = breaker.members_by_axis[other][0]
        pairs += [(leader, follower), (follower, leader)]
    return pairs


def build_resolution_pairs(
    breaker: PolarityTieBreaker, normalized: str
) -> list[tuple[str, str]]:
    involved = find_axes_with_evidence(breaker, normalized)
    if not involved:
        first_axis = next(iter(breaker.members_by_axis.values()))
        return [(first_axis[0], first_axis[1])]

    pairs = [
        pair
        for axis in involved
        for pair in permutations(breaker.members_by_axis[axis], 2)
    ]
    return pairs + build_cross_axis_pairs(breaker, involved)


def build_case(breaker: PolarityTieBreaker, utterance: str) -> dict:
    normalized = normalize_utterance(utterance)
    return {
        "utterance": utterance,
        "normalized": normalized,
        "resolutions": [
            [
                leader,
                runner_up,
                breaker.resolve(normalized, [(leader, 1.0), (runner_up, 0.9)]).winner,
            ]
            for leader, runner_up in build_resolution_pairs(breaker, normalized)
        ],
    }


def build_payload(breaker: PolarityTieBreaker, utterances: list[str]) -> dict:
    return {
        "_comment": HEADER_COMMENT,
        "table_term_counts": {
            route: len(terms) for route, terms in breaker.terms_by_route.items()
        },
        "cases": [build_case(breaker, utterance) for utterance in utterances],
    }


def render_payload(payload: dict) -> str:
    """One case per line, so a regeneration diff shows which utterances moved.

    `json.dumps` indents every nesting level or none of them, and neither reads
    well here: fully indented puts each route id on its own line and buries the
    change, fully compact puts the whole corpus on one line.
    """
    header = {key: value for key, value in payload.items() if key != "cases"}
    lines = [json.dumps(case, ensure_ascii=False, separators=(",", ":")) for case in payload["cases"]]
    body = ",\n  ".join(lines)
    return (
        json.dumps(header, ensure_ascii=False, indent=1)[:-2]
        + ',\n "cases": [\n  '
        + body
        + "\n ]\n}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(CASES_PATH))
    arguments = parser.parse_args()

    breaker = load_tie_breaker()
    payload = build_payload(breaker, collect_utterances())

    output_path = Path(arguments.output)
    output_path.write_text(render_payload(payload), encoding="utf-8")

    resolutions = [
        resolution for case in payload["cases"] for resolution in case["resolutions"]
    ]
    swaps = sum(winner != leader for leader, _, winner in resolutions)
    print(f"{output_path} — {len(payload['cases'])} utterances, {len(resolutions)} resolutions")
    print(f"  {swaps} of them promote the runner-up")


if __name__ == "__main__":
    main()
